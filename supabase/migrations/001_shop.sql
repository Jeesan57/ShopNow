begin;
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade);
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as $$ select exists(select 1 from admin_users where user_id = auth.uid()); $$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;
create table if not exists public.categories (name text primary key check(length(name) between 1 and 80));
create table if not exists public.products (
 id bigint generated by default as identity primary key, name text not null check(length(name) between 1 and 200), description text not null default '',
 price numeric(12,2) not null check(price >= 0), image text not null, category text not null references categories(name) on update cascade,
 sizes text[] not null default '{One Size}' check(cardinality(sizes)>0), thumbnails text[] not null default '{}', stock integer not null default 0 check(stock >= 0),
 active boolean not null default false, featured boolean not null default false, created_at timestamptz not null default now());
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(), customer_name text not null, email text not null, phone text not null, address text not null,
 total numeric(12,2) not null check(total>=0), status text not null default 'pending' check(status in ('pending','confirmed','shipped','delivered','cancelled')),
 payment_method text not null default 'cash_on_delivery' check(payment_method='cash_on_delivery'), created_at timestamptz not null default now());
create table if not exists public.order_items (
 id bigint generated always as identity primary key, order_id uuid not null references orders(id) on delete cascade,
 product_id bigint references products(id) on delete set null, name text not null, size text not null, quantity integer not null check(quantity>0), price numeric(12,2) not null);
create table if not exists public.messages (
 id uuid primary key default gen_random_uuid(), name text not null check(length(name) between 1 and 200), email text not null check(length(email) between 3 and 254),
 subject text not null check(length(subject) between 1 and 300), message text not null check(length(message) between 1 and 5000),
 read boolean not null default false, created_at timestamptz not null default now());
alter table admin_users enable row level security;
alter table categories enable row level security;
alter table products enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;
alter table messages enable row level security;
create policy "Own admin membership" on admin_users for select to authenticated using(user_id=auth.uid());
create policy "Public categories" on categories for select to anon,authenticated using(true);
create policy "Manage categories" on categories for all to authenticated using(is_admin()) with check(is_admin());
create policy "Published catalog" on products for select to anon,authenticated using(active or is_admin());
create policy "Manage catalog" on products for all to authenticated using(is_admin()) with check(is_admin());
create policy "Manage orders" on orders for all to authenticated using(is_admin()) with check(is_admin());
create policy "Manage order items" on order_items for select to authenticated using(is_admin());
create policy "Manage messages" on messages for all to authenticated using(is_admin()) with check(is_admin());
grant select on categories,products to anon;
grant select,insert,update,delete on categories,products,orders,messages to authenticated;
grant select on admin_users,order_items to authenticated;
grant usage,select on all sequences in schema public to authenticated;
create or replace function public.submit_message(p_name text,p_email text,p_subject text,p_message text) returns void language plpgsql security definer set search_path=public as $$
begin
 if p_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then raise exception 'Enter a valid email address'; end if;
 insert into messages(name,email,subject,message) values(trim(p_name),trim(p_email),trim(p_subject),trim(p_message));
end; $$;
create or replace function public.place_order(p_name text,p_email text,p_phone text,p_address text,p_items jsonb) returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid; v_item jsonb; v_product products%rowtype; v_qty integer; v_total numeric:=0; v_size text;
begin
 if length(trim(p_name)) not between 1 and 200 or length(p_email)>254 or p_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' or length(trim(p_phone)) not between 5 and 40 or length(trim(p_address)) not between 5 and 1000 then raise exception 'Enter valid contact and shipping details'; end if;
 if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 100 then raise exception 'Your cart is empty or too large'; end if;
 insert into orders(customer_name,email,phone,address,total) values(trim(p_name),lower(trim(p_email)),trim(p_phone),trim(p_address),0) returning id into v_id;
 for v_item in select value from jsonb_array_elements(p_items) order by (value->>'id')::bigint loop
  v_qty := (v_item->>'quantity')::integer; v_size:=v_item->>'size';
  select * into v_product from products where id=(v_item->>'id')::bigint and active for update;
  if not found or v_qty is null or v_qty not between 1 and 100 or v_product.stock < v_qty or v_size is null or not(v_size=any(v_product.sizes)) then raise exception 'An item is unavailable, out of stock, or has an invalid size'; end if;
  insert into order_items(order_id,product_id,name,size,quantity,price) values(v_id,v_product.id,v_product.name,v_size,v_qty,v_product.price);
  update products set stock=stock-v_qty where id=v_product.id;
  v_total:=v_total+v_product.price*v_qty;
 end loop;
 update orders set total=v_total where id=v_id;
 return v_id;
end; $$;
revoke all on function public.place_order(text,text,text,text,jsonb), public.submit_message(text,text,text,text) from public;
grant execute on function public.place_order(text,text,text,text,jsonb), public.submit_message(text,text,text,text) to anon,authenticated;
